void OLED_DrawPoint(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    if (color) OLED_SET_PIXEL(x, y);
    else       OLED_CLR_PIXEL(x, y);
}

void OLED_DrawLine(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t color)
{
    int16_t dx  = (int16_t)abs((int)x1 - (int)x0);
    int16_t dy  = -(int16_t)abs((int)y1 - (int)y0);
    int16_t sx  = (x0 < x1) ? 1 : -1;
    int16_t sy  = (y0 < y1) ? 1 : -1;
    int16_t err = dx + dy;

    for (;;) {
        OLED_DrawPoint(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int16_t e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 = (uint8_t)(x0 + sx); }
        if (e2 <= dx) { err += dx; y0 = (uint8_t)(y0 + sy); }
    }
}

void OLED_DrawRect(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t color, uint8_t fill)
{
    if (fill) {
        for (uint8_t y = y0; y <= y1; y++)
            for (uint8_t x = x0; x <= x1; x++)
                OLED_DrawPoint(x, y, color);
    } else {
        OLED_DrawLine(x0, y0, x1, y0, color);
        OLED_DrawLine(x1, y0, x1, y1, color);
        OLED_DrawLine(x1, y1, x0, y1, color);
        OLED_DrawLine(x0, y1, x0, y0, color);
    }
}

void OLED_DrawCircle(uint8_t cx, uint8_t cy, uint8_t r, uint8_t color, uint8_t fill)
{
    int16_t x = 0, y = r, d = 3 - 2 * r;

    while (x <= y) {
        if (fill) {
            for (int16_t i = cx - x; i <= cx + x; i++) {
                OLED_DrawPoint((uint8_t)i, (uint8_t)(cy - y), color);
                OLED_DrawPoint((uint8_t)i, (uint8_t)(cy + y), color);
            }
            for (int16_t i = cx - y; i <= cx + y; i++) {
                OLED_DrawPoint((uint8_t)i, (uint8_t)(cy - x), color);
                OLED_DrawPoint((uint8_t)i, (uint8_t)(cy + x), color);
            }
        } else {
            OLED_DrawPoint((uint8_t)(cx + x), (uint8_t)(cy - y), color);
            OLED_DrawPoint((uint8_t)(cx - x), (uint8_t)(cy - y), color);
            OLED_DrawPoint((uint8_t)(cx + x), (uint8_t)(cy + y), color);
            OLED_DrawPoint((uint8_t)(cx - x), (uint8_t)(cy + y), color);
            OLED_DrawPoint((uint8_t)(cx + y), (uint8_t)(cy - x), color);
            OLED_DrawPoint((uint8_t)(cx - y), (uint8_t)(cy - x), color);
            OLED_DrawPoint((uint8_t)(cx + y), (uint8_t)(cy + x), color);
            OLED_DrawPoint((uint8_t)(cx - y), (uint8_t)(cy + x), color);
        }
        if (d < 0)      d += 4 * x + 6;
        else            { d += 4 * (x - y) + 10; y--; }
        x++;
    }
}

/* ===================== ?? / ?? ===================== */
void OLED_ShowBMP(uint8_t x, uint8_t y, uint8_t w, uint8_t h, const uint8_t *bmp)
{
    uint8_t pages = (h + 7) / 8;

    for (uint8_t py = 0; py < pages; py++) {
        for (uint8_t cx = 0; cx < w; cx++) {
            if ((x + cx) < OLED_WIDTH && ((y >> 3) + py) < 8) {
                OLED_GRAM[(y >> 3) + py][x + cx] = bmp[py * w + cx];
            }
        }
    }
}

