static void OLED_WriteCmd(uint8_t cmd)
{
    HAL_I2C_Mem_Write(&OLED_I2C_HANDLE, OLED_I2C_ADDR, 0x00,
                      I2C_MEMADD_SIZE_8BIT, &cmd, 1, 100);
}

static void OLED_WriteData(const uint8_t *data, uint16_t len)
{
    HAL_I2C_Mem_Write(&OLED_I2C_HANDLE, OLED_I2C_ADDR, 0x40,
                      I2C_MEMADD_SIZE_8BIT, (uint8_t *)data, len, 100);
}

