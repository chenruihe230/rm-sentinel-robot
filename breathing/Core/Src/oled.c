static uint8_t OLED_CharWidth(uint8_t size)
{
    return (size == OLED_SIZE_8) ? 6 : 8;
}

void OLED_ShowChar(uint8_t x, uint8_t y, uint8_t chr, uint8_t size, uint8_t mode)
{
    uint8_t c, i, j;

    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    if (size == OLED_SIZE_8 && x + 6 > OLED_WIDTH)  return;
    if (size == OLED_SIZE_16 && x + 8 > OLED_WIDTH) return;
    if (y + size > OLED_HEIGHT) return;

    c = chr - ' ';
    if (c > 94) return;

    if (size == OLED_SIZE_8) {
        for (i = 0; i < 6; i++) {
            uint8_t col = OLED_6x8[c][i];
            for (j = 0; j < 8; j++) {
                if (col & 0x01)      OLED_SET_PIXEL(x + i, y + j);
                else if (mode == OLED_MODE_INVERSE) OLED_CLR_PIXEL(x + i, y + j);
                col >>= 1;
            }
        }
    } else {
        for (i = 0; i < 8; i++) {
            uint8_t col_up = OLED_8x16[c][i];        /* ???? 0~7  */
            uint8_t col_dn = OLED_8x16[c][i + 8];    /* ???? 8~15 */
            for (j = 0; j < 8; j++) {
                if (col_up & 0x01)      OLED_SET_PIXEL(x + i, y + j);
                else if (mode == OLED_MODE_INVERSE) OLED_CLR_PIXEL(x + i, y + j);
                if (col_dn & 0x01)      OLED_SET_PIXEL(x + i, y + 8 + j);
                else if (mode == OLED_MODE_INVERSE) OLED_CLR_PIXEL(x + i, y + 8 + j);
                col_up >>= 1;
                col_dn >>= 1;
            }
        }
    }
}

void OLED_ShowString(uint8_t x, uint8_t y, const char *str, uint8_t size, uint8_t mode)
{
    uint8_t w = OLED_CharWidth(size);

    while (*str && (x + w <= OLED_WIDTH)) {
        OLED_ShowChar(x, y, (uint8_t)*str, size, mode);
        x += w;
        str++;
    }
}

void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len, uint8_t size)
{
    uint8_t  w = OLED_CharWidth(size);
    uint16_t cur = x + (uint16_t)(len - 1) * w;     /* ???????? */

    for (uint8_t i = 0; i < len; i++) {
        OLED_ShowChar((uint8_t)cur, y, (uint8_t)('0' + num % 10), size, OLED_MODE_NORMAL);
        cur -= w;
        num /= 10;
    }
}

void OLED_ShowSignedNum(uint8_t x, uint8_t y, int32_t num, uint8_t len, uint8_t size)
{
    uint8_t w = OLED_CharWidth(size);

    if (num < 0) {
        OLED_ShowChar(x, y, '-', size, OLED_MODE_NORMAL);
        num = -num;
    } else {
        OLED_ShowChar(x, y, ' ', size, OLED_MODE_NORMAL);
    }
    OLED_ShowNum(x + w, y, (uint32_t)num, len - 1, size);
}

void OLED_ShowHex(uint8_t x, uint8_t y, uint32_t num, uint8_t len, uint8_t size)
{
    uint8_t w = OLED_CharWidth(size);

    for (uint8_t i = 0; i < len; i++) {
        uint8_t d  = (uint8_t)((num >> ((len - 1 - i) * 4)) & 0x0F);
        uint8_t ch = (d < 10) ? (uint8_t)('0' + d) : (uint8_t)('A' + d - 10);
        OLED_ShowChar(x + i * w, y, ch, size, OLED_MODE_NORMAL);
    }
}

void OLED_ShowFloat(uint8_t x, uint8_t y, float num, uint8_t ilen, uint8_t dlen, uint8_t size)
{
    static const uint32_t pow10[] = {1, 10, 100, 1000, 10000, 100000, 1000000, 10000000};
    uint8_t  w   = OLED_CharWidth(size);
    uint16_t cur = x;

    if (num < 0) {
        OLED_ShowChar(x, y, '-', size, OLED_MODE_NORMAL);
        cur += w;
        num = -num;
    }

    uint32_t ip = (uint32_t)num;
    uint32_t dp = (uint32_t)((num - (float)ip) * (float)pow10[dlen] + 0.5f);
    if (dp >= pow10[dlen]) {        /* ?????? */
        dp = 0;
        ip += 1;
    }

    OLED_ShowNum((uint8_t)cur, y, ip, ilen, size);
    cur += (uint16_t)ilen * w;
    OLED_ShowChar((uint8_t)cur, y, '.', size, OLED_MODE_NORMAL);
    cur += w;
    OLED_ShowNum((uint8_t)cur, y, dp, dlen, size);
}

