void OLED_Clear(void)
{
    memset(OLED_GRAM, 0x00, sizeof(OLED_GRAM));
}

void OLED_Fill(void)
{
    memset(OLED_GRAM, 0xFF, sizeof(OLED_GRAM));
}

void OLED_Refresh(void)
{
    for (uint8_t page = 0; page < 8; page++) {
        OLED_WriteCmd(0xB0 + page);     /* ??? 0~7        */
        OLED_WriteCmd(0x00);            /* ???? 4 ?     */
        OLED_WriteCmd(0x10);            /* ???? 4 ?     */
        OLED_WriteData(OLED_GRAM[page], OLED_WIDTH);
    }
}

void OLED_DisplayOn(void)   { OLED_WriteCmd(0xAF); }
void OLED_DisplayOff(void)  { OLED_WriteCmd(0xAE); }

