#define OLED_SET_PIXEL(x, y)    (OLED_GRAM[(y) >> 3][(x)] |=  (1u << ((y) & 7)))
#define OLED_CLR_PIXEL(x, y)    (OLED_GRAM[(y) >> 3][(x)] &= ~(1u << ((y) & 7)))

