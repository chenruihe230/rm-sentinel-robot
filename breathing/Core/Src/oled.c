void OLED_ShowChinese(uint8_t x, uint8_t y, uint8_t index, uint8_t size)
{
    uint8_t i, j;

    if (size != OLED_SIZE_16) return;
    if (x + 16 > OLED_WIDTH || y + 16 > OLED_HEIGHT) return;

    for (i = 0; i < 16; i++) {
        uint8_t up = OLED_Hz16[index][i];
        uint8_t dn = OLED_Hz16[index][i + 16];
        for (j = 0; j < 8; j++) {
            if (up & 0x01) OLED_SET_PIXEL(x + i, y + j);
            if (dn & 0x01) OLED_SET_PIXEL(x + i, y + 8 + j);
            up >>= 1;
            dn >>= 1;
        }
    }
}

